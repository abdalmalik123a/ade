import { describe, expect, it } from 'vitest';
import { cleanIdOcrText } from '../src/shared/idOcrText';

describe('S33: عناوين المستمسك في العرض فقط', () => {
  it.each([
    ['الاسم / ناو : زينب علي حسن', 'الاسم : زينب علي حسن'],
    ['الأب / باوک : علي', 'الأب : علي'],
    ['الجد بيهر : حسن', 'الجد : حسن'],
    ['الجد / باپیر : كريم', 'الجد : كريم'],
    ['اللقب /نازناو: الموسوي', 'اللقب: الموسوي'],
    ['الأم /ديك : هناء', 'الأم : هناء'],
    ['الجنس / ڕەگەز : أنثى', 'الجنس : أنثى'],
    ['فصيلة الدم / گروپی خوێن : O+', 'فصيلة الدم : O+'],
    ['محل الولادة / شوێنی لەدایک بوون : بغداد', 'محل الولادة : بغداد'],
    ['تاريخ الولادة / ڕۆژی لەدایک بوون : 1990/01/15', 'تاريخ الولادة : 1990/01/15'],
    ['تاريخ الإصدار / روزى ده رچوون : ٢٠٢٠/٠٢/٠٣', 'تاريخ الإصدار : ٢٠٢٠/٠٢/٠٣'],
    ['تاريخ النفاذ /روزى بمسبرجوون : 2030/02/03', 'تاريخ النفاذ : 2030/02/03'],
    ['جهة الإصدار / لایەنی دەرچوون : مديرية مصنوعة', 'جهة الإصدار : مديرية مصنوعة'],
    ['الرقم العائلي / ژمارەی خێزانی : 1234TEST', 'الرقم العائلي : 1234TEST'],
    ['رقم الجواز / ژمارەی پاسپۆرت : Z12345678', 'رقم الجواز : Z12345678'],
    ['الجنسية / ڕەگەزنامە : عراقي', 'الجنسية : عراقي'],
    ['\u200fالأم /\u200eدايك\u200f : \u200fهناء', '\u200fالأم : \u200fهناء'],
    ['  الأُمّ\t|\tدایک\t：هناء', '  الأُمّ\t：هناء']
  ])('ينقّي %s', (source, expected) => {
    expect(cleanIdOcrText(source)).toBe(expected);
    expect(cleanIdOcrText(expected)).toBe(expected);
  });
  it.each([
    'الاسم : ناو حسن علي', 'الاسم: زينب / ناو', 'ملاحظات : الأم / ديك',
    'الاسم / عنوان مجهول : زينب', 'الأم / ناو : هناء', 'ناو / الاسم : زينب',
    'الاسم / ناو / لقب : زينب', 'الأم / دايك هناء : نص مجهول',
    'الاسم / ناو', 'ناو باوک ڕەگەز', 'قال سالم إن الاسم / ناو : عنوان مطبوع',
    'الاسم : قيمة / ناو : قيمة أخرى', 'الاسم : زينب\nديك : اسم محتمل',
    'P<IRQHASSAN<<ZAINAB<ALI<<<<<<<<<<<<<<<<<<<<<<<\nZ123456787IRQ9001159F3102200<<<<<<<<<<<<<<<<<02', ''
  ])('يحفظ الملتبس والقيمة والأصل: %s', (text) => expect(cleanIdOcrText(text)).toBe(text));
  it('يحفظ فواصل الأسطر والأرقام والقيم حرفيًا، ولا يغيّر المصدر', () => {
    const source = 'الاسم / ناو : زينب علي حسن\r\n\r\nالرقم: ١٢٣TEST\nالأم /ديك : ناو / ديك';
    expect(cleanIdOcrText(source)).toBe('الاسم : زينب علي حسن\r\n\r\nالرقم: ١٢٣TEST\nالأم : ناو / ديك');
    expect(source).toContain('الأم /ديك');
  });
});
