/**
 * مفاتيح ما يُتعلَّم ولا يُقرأ من نصٍّ بعينه (ج١٣).
 *
 * «أهذان نسخةٌ واحدة؟» لا مدخل له إلا درجة التشابه: فتُجمع في شرائح (٩٥٪، ٩٠٪…)
 * ويُسأل: أيُبقي هذا المكتب ما تشابه بهذه الدرجة؟ — مكتبٌ يحفظ «تأييد (ذكور)»
 * و«تأييد (إناث)» نموذجين يعلّم البرنامج ألّا ينزع اختيار أحدهما.
 */
export function similarityBucket(confidence: number): string {
  const pct = Math.max(0, Math.min(100, Math.round(confidence * 100)));
  return `${Math.floor(pct / 5) * 5}`;
}
