/**
 * تهريب النصّ في HTML (ز٢) — نسخةٌ واحدة بعد ثلاثٍ متطابقة (`docHtml` و`pdfEdit` و`watermark`).
 *
 * ونصٌّ يقع في خاصّية (`src="…"`) تُهرَّب علامته `"` أيضًا — وإلا قطع اسمُ ملفٍّ أو قيمةٌ فيها علامة تنصيص الخاصّية
 * وفتح غيرها (خطة Production، ٢٫٥). و`&quot;` ممّا يفكّه `htmlToText`، فالنصّ المستخرج للبحث والبصمة لا يتغيّر.
 * ولا تُهرَّب `'`: خصائص البرنامج كلّها بين علامتين مزدوجتين، وتهريبها يغيّر نصّ الكتب المحفوظة وبصمتها.
 */
export const escapeHtml = (s: string): string =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
