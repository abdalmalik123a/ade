/**
 * حجم الخطّ بالنقطة كما في Word (د٥). كان المحرّر يعرض البكسل: «١٦» من Word يظهر «٢١»، والأساس ١٤ بكسلًا
 * (≈ ١٠٫٥ نقطة) — فمن يختار «١٦» ظانًّا أنه نقطة يحصل على ١٢ نقطة.
 *
 * **والتخزين بالبكسل كما كان** (عقدة `size` بـ`px`): فالكتب القديمة تُقرأ كما هي، والعرض وحده يتحوّل.
 * والبكسل يُحفظ بمنزلتين لا مقرَّبًا إلى عددٍ صحيح — فـ١٦ نقطةً تُختار في المحرّر هي ١٦ نقطةً تأتي من Word
 * (`docxDoc.ts`: نصف النقطة × ٩٦/٧٢) لا ٢١ بكسلًا مقابل ٢١٫٣٣.
 */

/** نقطةٌ واحدة = ٩٦/٧٢ بكسل في CSS — وبالعكس ٠٫٧٥. */
export const PT_PER_PX = 0.75;

/** الأحجام الشائعة في قائمة Word. */
export const WORD_SIZES_PT: readonly number[] = [8, 9, 10, 10.5, 11, 12, 14, 16, 18, 20, 24, 28, 36, 48, 72];

/** البكسل المخزَّن ← النقطة المعروضة، لأقرب نصف نقطة (كما يعرض Word). */
export function pxToPt(px: number): number {
  return Math.round(px * PT_PER_PX * 2) / 2;
}

/** النقطة المختارة ← البكسل المخزَّن، بمنزلتين. */
export function ptToPx(pt: number): number {
  return Math.round((pt / PT_PER_PX) * 100) / 100;
}
